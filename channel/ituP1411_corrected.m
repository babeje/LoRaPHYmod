function L = ituP1411_corrected(freq_MHz, d_m, hTx_m, hRx_m, elevAngle_deg)
    % ituP1411_corrected — потери распространения по ITU-R P.1411-10
    % для городской среды, короткие трассы (до ~1 км), 868 МГц.
    %
    % Аргументы:
    %   freq_MHz      — несущая частота, МГц
    %   d_m           — расстояние между узлами, м (3D)
    %   hTx_m         — высота передающей антенны над землёй, м
    %   hRx_m         — высота приёмной антенны над землёй, м
    %   elevAngle_deg — угол места (elevation angle), градусы
    %
    % Возвращает:
    %   L — полные потери распространения, дБ
    %
    % Модель:
    %   LOS  — двухлучевая модель с точкой перегиба (breakpoint).
    %          До breakpoint: FSPL; после — +20 дБ/дек дополнительно.
    %          ITU-R P.1411-10, формула (1).
    %
    %   NLOS — степенной закон с экспонентой пути n_path.
    %          L = L_ref(1 м) + 10 * n_path * log10(d_m)
    %          Физически корректен при любом расстоянии: L >= FSPL(1 м).
    %          Экспонента n_path = 3.8 соответствует плотной городской
    %          застройке, 868 МГц, по данным ITU-R P.1411-10 и измерениям.
    %
    % Примечание по предыдущей версии:
    %   Формула L_excess = 20 + 30*log10(d_km) даёт отрицательные значения
    %   при d < 1 км (например, -10 дБ при d=100 м), что физически некорректно:
    %   NLOS не может быть лучше FSPL. Заменена на степенной закон.
    %
    % Ссылки:
    %   ITU-R P.1411-10 (08/2019), разделы 4.1, 4.2, таблица 1.
    %   D. Zorbas et al., IEEE IoT Journal, vol. 6, no. 5, pp. 9087-9095, 2019.

    % Минимальное расстояние для устойчивости формул
    d_m = max(d_m, 1.0);

    % --- Потери свободного пространства (FSPL) ---
    % FSPL = 20*log10(4*pi*d*f/c) = 20*log10(d_m) + 20*log10(f_MHz) - 27.55
    FSPL   = 20*log10(d_m) + 20*log10(freq_MHz) - 27.55;
    L_ref1 = 20*log10(1.0) + 20*log10(freq_MHz) - 27.55;   % FSPL на 1 м

    % --- Длина волны ---
    lambda_m = (3e8) / (freq_MHz * 1e6);   % м

    if elevAngle_deg > 5
        % ============================================================
        %  LOS-условия: двухлучевая модель с точкой перегиба
        % ============================================================
        % Точка перегиба d_break: расстояние, при котором отражённый
        % луч начинает вносить значимый деструктивный вклад.
        d_break = 4 * hTx_m * hRx_m / lambda_m;   % м

        if d_m <= d_break
            L = FSPL;
        else
            % После breakpoint: +20 дБ/дек относительно FSPL(d_break)
            L = FSPL + 20*log10(d_m / d_break);
        end

    else
        % ============================================================
        %  NLOS-условия: степенной закон с экспонентой пути
        % ============================================================
        % L(d) = L_ref(1 м) + 10 * n_path * log10(d_m)
        %
        % При d=1 м: L = FSPL(1 м); при d > 1 м нарастает быстрее
        % FSPL из-за дифракции, рассеяния и переотражений.
        %
        % n_path = 3.8 — плотная городская застройка, 868 МГц:
        %   n = 2.0  — свободное пространство
        %   n = 2.5  — пригород, малоэтажная застройка
        %   n = 3.5  — городская застройка (типовое)
        %   n = 3.8  — плотная городская застройка (данная работа)
        %   n = 4.5  — закрытые помещения
        n_path = 3.8;
        L = L_ref1 + 10 * n_path * log10(d_m);
    end

    % Физическое ограничение снизу: потери не могут быть меньше FSPL
    L = max(L, FSPL);
end
