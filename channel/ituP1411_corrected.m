function L = ituP1411_corrected(freq_MHz, d_m, hTx_m, hRx_m, elevAngle_deg)
    % ituP1411_corrected — потери распространения по ITU-R P.1411-10
    % для городской среды, короткие трассы (до ~1 км).
    %
    % Аргументы:
    %   freq_MHz      — несущая частота, МГц
    %   d_m           — расстояние между узлами, м (3D)
    %   hTx_m         — высота передающей антенны над землёй, м
    %   hRx_m         — высота приёмной антенны над землёй, м
    %   elevAngle_deg — угол места (elevation angle), градусы
    %
    % Возвращает:
    %   L — полные потери распространения, дБ
    %
    % Физическая корректность:
    %   - hTx_m, hRx_m — высота над землёй в метрах (типично 1.5...150 м),
    %     а не длина антенны.
    %   - Потери свободного пространства (FSPL) вычисляются по стандартной
    %     формуле ITU-R P.525.
    %   - LOS / NLOS определяется по углу места: при elevAngle > 5° считаем
    %     условиями близкими к LOS; иначе — NLOS (городская застройка).
    %
    % Ссылка: ITU-R P.1411-10 (08/2019), раздел 4.1 (LOS) и 4.2 (NLOS).

    % Минимальное расстояние для устойчивости формул
    d_m = max(d_m, 1.0);

    % Потери свободного пространства (Free Space Path Loss), дБ
    % FSPL = 20*log10(d) + 20*log10(f_MHz) + 20*log10(4*pi/c)
    %      = 20*log10(d_m) + 20*log10(f_MHz) - 27.55
    FSPL = 20*log10(d_m) + 20*log10(freq_MHz) - 27.55;

    if elevAngle_deg > 5
        % ====== LOS-условия ======
        % ITU-R P.1411-10, формула (1): медианные потери LOS
        % L_LOS = FSPL + L_correction
        % Поправка учитывает отражения от земли при известных высотах антенн.
        % При высотах > длины волны доминирует двухлучевая модель:
        %   correction = -20*log10(hTx_m * hRx_m / d_m^2)  [для d >> breakpoint]
        % Для расстояний до точки перегиба используем упрощённую форму:
        lambda_m = 0.3 / freq_MHz * 1e3;   % длина волны, м (c = 3e8 м/с)
        d_break  = 4 * hTx_m * hRx_m / lambda_m;   % расстояние точки перегиба

        if d_m < d_break
            % До точки перегиба — FSPL плюс малая поправка
            L = FSPL;
        else
            % После точки перегиба — модель двухлучевого распространения:
            %   L = 40*log10(d) - 20*log10(hTx * hRx)  (в дБ, относительно 1м/1МГц)
            % Пересчитываем относительно FSPL:
            L = FSPL + 20*log10(d_m / d_break);
        end

    else
        % ====== NLOS-условия (городская застройка) ======
        % ITU-R P.1411-10, формула (11): потери за углом здания.
        % Упрощённая форма для ненаправленных антенн:
        %   L_NLOS = FSPL + L_excess
        % L_excess — дополнительные потери из-за дифракции и рассеяния.
        % Эмпирически для плотной городской застройки: 20..35 дБ сверх FSPL,
        % возрастающие с расстоянием.
        d_km = d_m / 1000;
        L_excess = 20 + 30*log10(max(d_km, 0.01));

        % Поправка на высоту приёмника (снижение потерь при большей высоте)
        % Типовая зависимость: -0.8 дБ на каждый метр высоты RX (эмпирически)
        L_height = -0.8 * min(hRx_m, 30);  % ограничиваем эффект до 30 м

        L = FSPL + L_excess + L_height;
    end

    % Нижняя граница — не меньше FSPL (физическое ограничение)
    L = max(L, FSPL);
end
