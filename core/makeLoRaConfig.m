function cfg = makeLoRaConfig(rf_freq, sf, bw, fs)
% makeLoRaConfig  Фабрика неизменяемой конфигурации физического уровня LoRa.
%
% Назначение:
%   Единый источник истины по PHY-параметрам и их производным величинам
%   в МОДЕМНОМ соглашении о передискертизации (os = fs / bw). Устраняет
%   дублирование ручных пересчётов (os, N, Ns), разбросанных по методам
%   LoRaModem и по сценариям.
%
%   Функция реализует value-object как обычную struct (data-oriented подход,
%   «functional core»): неизменяемость обеспечивается семантикой копирования
%   struct по значению; все производные вычисляются один раз при создании.
%
% Разграничение соглашений (важно):
%   Здесь используется ТОЛЬКО модемное соглашение os = fs / bw.
%   Внутренние величины форка LoRaPHY (sample_num, bin_num, fft_len)
%   определены в ДРУГОМ соглашении (передискретизация 2·bw) и намеренно
%   НЕ выносятся сюда: смешение двух соглашений в одной структуре —
%   источник скрытых ошибок. Они остаются инкапсулированными в LoRaPHY.
%
% Вход:
%   rf_freq [Гц] — несущая частота (carrier frequency)
%   sf           — spreading factor (целое, 7..12)
%   bw      [Гц] — полоса сигнала (bandwidth)
%   fs      [Гц] — частота дискретизации (sampling rate)
%
% Выход:
%   cfg [struct] — конфигурация со следующими полями:
%       .rf_freq — несущая, Гц (первичный параметр)
%       .sf      — spreading factor (первичный параметр)
%       .bw      — полоса, Гц (первичный параметр)
%       .fs      — частота дискретизации, Гц (первичный параметр)
%       .N       — число чипов на символ:            N  = 2^sf
%       .os      — коэффициент передискретизации:     os = fs / bw
%       .Ns      — число отсчётов на символ:           Ns = N * os
%
% Совместимость: MATLAB R2024a, без дополнительных тулбоксов.
% ---------------------------------------------------------------

    % --- Валидация входных параметров (fail-fast) ---
    validateattributes(rf_freq, {'numeric'}, {'scalar', 'real', 'positive'}, ...
        mfilename, 'rf_freq');
    validateattributes(sf, {'numeric'}, ...
        {'scalar', 'integer', '>=', 7, '<=', 12}, mfilename, 'sf');
    validateattributes(bw, {'numeric'}, {'scalar', 'real', 'positive'}, ...
        mfilename, 'bw');
    validateattributes(fs, {'numeric'}, {'scalar', 'real', 'positive'}, ...
        mfilename, 'fs');

    % --- Первичные параметры ---
    cfg.rf_freq = rf_freq;
    cfg.sf      = sf;
    cfg.bw      = bw;
    cfg.fs      = fs;

    % --- Производные величины (модемное соглашение os = fs/bw) ---
    cfg.N  = 2^sf;              % чипов на символ
    cfg.os = fs / bw;          % коэффициент передискретизации
    cfg.Ns = cfg.N * cfg.os;   % отсчётов на символ

    % --- Инвариант: посимвольная нарезка сигнала требует целого Ns ---
    % Нарушение означает несовместимость (fs, bw, sf) с модемной обработкой.
    assert(abs(cfg.Ns - round(cfg.Ns)) < eps(cfg.Ns) * 8, ...
        'makeLoRaConfig:nonIntegerNs', ...
        ['Число отсчётов на символ Ns = %.6f не целое ', ...
         '(2^sf · fs/bw). Проверьте согласованность fs, bw, sf.'], cfg.Ns);
end
